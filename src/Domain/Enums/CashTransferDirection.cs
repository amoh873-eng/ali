namespace ERPSystem.Domain.Enums;

/// <summary>
/// اتجاه تحويل النقد بين موقعين نقديين (الخزنة الرئيسية «الصندوق» 1100 ↔ درج الكاش 1105).
/// ليست مصروفاً ولا إيراداً — مجرد نقل نفس المال من حساب نقدي إلى آخر.
/// </summary>
public enum CashTransferDirection
{
    /// <summary>
    /// تمويل درج الكاش: تحويل من الخزنة الرئيسية (الصندوق) إلى درج الكاش (بداية الوردية / توفير فكة).
    /// القيد: مدين «درج الكاش» 1105 / دائن «الصندوق» 1100.
    /// </summary>
    FloatIn = 1,

    /// <summary>
    /// سحب نقد من درج الكاش: تحويل من درج الكاش إلى الخزنة الرئيسية (نهاية الوردية / تحصين مبلغ كبير).
    /// القيد: مدين «الصندوق» 1100 / دائن «درج الكاش» 1105.
    /// </summary>
    CashOut = 2
}
